"""Generation (LLM) provider abstraction.

Swappable via config. The default `fake` provider is deterministic and offline:
it produces a grounded, citation-shaped answer built directly from the supplied
evidence, so chat and the answer API are testable without a model. Real
generation uses an Ollama or OpenAI-compatible chat endpoint.

The knowledge base never depends on generation: if a model is unavailable,
retrieval and document management continue to work and the UI/API surface a
clear "model unavailable" state.
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from collections.abc import Iterator
from dataclasses import dataclass
from threading import BoundedSemaphore

import httpx

from app.config import settings

_OLLAMA_CALLS = BoundedSemaphore(1)


@dataclass
class LLMStatus:
    available: bool
    detail: str = ""


class LLMProvider(ABC):
    name: str
    model: str

    @abstractmethod
    def generate(self, system: str, user: str, *, max_output_tokens: int | None = None, thinking: bool = False) -> str:
        ...

    def stream(self, system: str, user: str, *, max_output_tokens: int | None = None, thinking: bool = False) -> Iterator[str]:
        # Default: yield the whole response once (providers may override).
        yield self.generate(system, user, max_output_tokens=max_output_tokens, thinking=thinking)

    @abstractmethod
    def health(self) -> LLMStatus:
        ...


class FakeEcho(LLMProvider):
    """Deterministic grounded responder used for offline dev + tests.

    It does not invent facts: it composes an answer that references the
    evidence block it was given, or abstains when no evidence is present.
    """

    name = "fake"

    def __init__(self, model: str = "fake-echo") -> None:
        self.model = model

    def generate(self, system: str, user: str, *, max_output_tokens: int | None = None, thinking: bool = False) -> str:
        has_evidence = "[E1]" in user or "EVIDENCE" in user.upper()
        if not has_evidence or "NO EVIDENCE" in user.upper():
            return (
                "I don't have enough indexed evidence to answer that confidently. "
                "No supporting passages were retrieved from the selected collections."
            )
        # Extract the question for a minimal grounded echo.
        question = ""
        for line in user.splitlines():
            if line.upper().startswith("QUESTION:"):
                question = line.split(":", 1)[1].strip()
                break
        return (
            f"Based on the retrieved evidence, here is a grounded summary"
            + (f" regarding: {question}" if question else "")
            + ". (Generated by the deterministic offline provider; configure a real model for natural-language synthesis.)"
        )

    def health(self) -> LLMStatus:
        return LLMStatus(available=True, detail="deterministic offline provider")


class OllamaChat(LLMProvider):
    name = "ollama"

    def __init__(self, model: str, base_url: str) -> None:
        self.model = model
        self.base_url = base_url.rstrip("/")

    def _payload(self, system: str, user: str, stream: bool, max_output_tokens: int | None, thinking: bool) -> dict:
        payload = {
            "model": self.model,
            "stream": stream,
            "options": {
                "temperature": settings.llm_temperature,
                "num_ctx": settings.llm_context_tokens,
                "num_predict": max_output_tokens or settings.llm_max_output_tokens,
            },
            "messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": user},
            ],
            "keep_alive": "30m",
        }
        if thinking:
            payload["think"] = True
        return payload

    @staticmethod
    def _raise_ollama_error(response: httpx.Response) -> None:
        if response.is_error:
            detail = response.read().decode("utf-8", errors="replace")[:800].strip()
            raise RuntimeError(f"Ollama returned {response.status_code}: {detail or response.reason_phrase}")

    @staticmethod
    def _thinking_unsupported(response: httpx.Response) -> bool:
        if response.status_code != 400:
            return False
        return "does not support thinking" in response.read().decode("utf-8", errors="replace").lower()

    @staticmethod
    def _stream_tokens(response: httpx.Response) -> Iterator[str]:
        import json

        for line in response.iter_lines():
            if not line:
                continue
            data = json.loads(line)
            piece = data.get("message", {}).get("content", "")
            if piece:
                yield piece

    def generate(self, system: str, user: str, *, max_output_tokens: int | None = None, thinking: bool = False) -> str:
        # Generous timeouts: connect quickly, but give the model plenty of
        # time for cold-start loading and full response generation.
        timeout = httpx.Timeout(
            connect=30.0,
            read=settings.llm_timeout_seconds,
            write=30.0,
            pool=30.0,
        )
        if not _OLLAMA_CALLS.acquire(timeout=settings.llm_timeout_seconds):
            raise TimeoutError("Another Ollama response is still running; retry shortly")
        try:
            with httpx.Client(timeout=timeout) as client:
                resp = client.post(
                    f"{self.base_url}/api/chat", json=self._payload(system, user, False, max_output_tokens, thinking)
                )
                if thinking and self._thinking_unsupported(resp):
                    resp = client.post(
                        f"{self.base_url}/api/chat",
                        json=self._payload(system, user, False, max_output_tokens, False),
                    )
                self._raise_ollama_error(resp)
                return resp.json()["message"]["content"]
        finally:
            _OLLAMA_CALLS.release()

    def stream(self, system: str, user: str, *, max_output_tokens: int | None = None, thinking: bool = False) -> Iterator[str]:
        # For streaming the read timeout applies *between chunks*, not to the
        # total response, so keep it generous for slow models / cold starts.
        timeout = httpx.Timeout(
            connect=30.0,
            read=settings.llm_timeout_seconds,
            write=30.0,
            pool=30.0,
        )
        if not _OLLAMA_CALLS.acquire(timeout=settings.llm_timeout_seconds):
            raise TimeoutError("Another Ollama response is still running; retry shortly")
        try:
            with httpx.Client(timeout=timeout) as client:
                payload = self._payload(system, user, True, max_output_tokens, thinking)
                fallback_thinking = False
                with client.stream("POST", f"{self.base_url}/api/chat", json=payload) as resp:
                    if thinking and self._thinking_unsupported(resp):
                        fallback_thinking = True
                    else:
                        self._raise_ollama_error(resp)
                        yield from self._stream_tokens(resp)
                if fallback_thinking:
                    fallback = self._payload(system, user, True, max_output_tokens, False)
                    with client.stream("POST", f"{self.base_url}/api/chat", json=fallback) as resp:
                        self._raise_ollama_error(resp)
                        yield from self._stream_tokens(resp)
        finally:
            _OLLAMA_CALLS.release()

    def health(self) -> LLMStatus:
        try:
            with httpx.Client(timeout=10.0) as client:
                resp = client.get(f"{self.base_url}/api/tags")
                resp.raise_for_status()
                models = [m["name"] for m in resp.json().get("models", [])]
            available = any(self.model in m for m in models)
            return LLMStatus(
                available=available,
                detail="model present" if available else f"model '{self.model}' not pulled",
            )
        except Exception as exc:
            return LLMStatus(available=False, detail=f"connection error: {exc}")


class OpenAICompatibleChat(LLMProvider):
    name = "openai"

    def __init__(self, model: str, base_url: str, api_key: str) -> None:
        self.model = model
        self.base_url = base_url.rstrip("/")
        self.api_key = api_key

    def _headers(self) -> dict:
        return {"Authorization": f"Bearer {self.api_key}"} if self.api_key else {}

    def generate(self, system: str, user: str, *, max_output_tokens: int | None = None, thinking: bool = False) -> str:
        with httpx.Client(timeout=settings.llm_timeout_seconds) as client:
            resp = client.post(
                f"{self.base_url}/v1/chat/completions",
                headers=self._headers(),
                json={
                    "model": self.model,
                    "temperature": settings.llm_temperature,
                    "max_tokens": max_output_tokens or settings.llm_max_output_tokens,
                    "messages": [
                        {"role": "system", "content": system},
                        {"role": "user", "content": user},
                    ],
                },
            )
            resp.raise_for_status()
            return resp.json()["choices"][0]["message"]["content"]

    def health(self) -> LLMStatus:
        try:
            with httpx.Client(timeout=5.0) as client:
                resp = client.get(f"{self.base_url}/v1/models", headers=self._headers())
                resp.raise_for_status()
            return LLMStatus(available=True, detail="endpoint reachable")
        except Exception as exc:
            return LLMStatus(available=False, detail=f"connection error: {exc}")


_provider: LLMProvider | None = None


def get_llm_provider() -> LLMProvider:
    global _provider
    if _provider is not None:
        return _provider
    if settings.disable_outbound_llm:
        _provider = FakeEcho(settings.llm_model)
        return _provider
    p = settings.llm_provider.lower()
    if p == "ollama":
        _provider = OllamaChat(settings.llm_model, settings.llm_base_url)
    elif p == "openai":
        _provider = OpenAICompatibleChat(
            settings.llm_model, settings.llm_base_url, settings.llm_api_key
        )
    else:
        _provider = FakeEcho(settings.llm_model)
    return _provider


def reset_llm_provider() -> None:
    global _provider
    _provider = None
